import Fastify from 'fastify';
import { mkdir } from 'node:fs/promises';
const app=Fastify({logger:true});
const dataDir=process.env.DATA_DIR??'/data';
app.get('/api/health',async()=>({status:'ok',component:'web',stage:'EPIC-01',scannerReady:false}));
app.get('/',async (_req,reply)=>reply.type('text/html').send('<!doctype html><html><head><meta charset="utf-8"><title>Headless SEO Inspector</title></head><body><h1>Headless SEO Inspector</h1><p>Foundation only. The authenticated panel is not available yet.</p></body></html>'));
const host=process.env.WEB_HOST??'127.0.0.1';
const port=Number(process.env.WEB_PORT??8080);
await mkdir(dataDir,{recursive:true});
const stop=async()=>{await app.close();process.exit(0);};
process.once('SIGTERM',()=>{void stop();});process.once('SIGINT',()=>{void stop();});
await app.listen({host,port});
